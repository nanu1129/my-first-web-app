  const unit = (id) => AP.lessons.flatMap((l) => l.units).find((u) => u.id === id);
  const missing = (msg) => { AP.lessonPatchErrors = (AP.lessonPatchErrors || []).concat(msg); console.error(`[lessons-deep] ${msg}`); };
  const section = (id, h) => {
    const u = unit(id);
    const sec = u && u.sections.find((s) => s.h === h);
    if (!sec) missing(`${id} / ${h} が見つかりません`);
    return sec;
  };

  function extend(id, h, o) {
    const sec = section(id, h);
    if (!sec) return;
    if (o.body) sec.body += `\n\n${o.body}`;
    if (o.points) sec.points = (sec.points || []).concat(o.points);
    if (o.tables) sec.tables = (sec.tables || (sec.table ? [sec.table] : [])).concat(o.tables);
    ['art', 'widget', 'example', 'code'].forEach((k) => { if (o[k]) sec[k] = o[k]; });
    if (o.example || o.tables) unit(id).minutes += 1;
    if (o.body) unit(id).minutes += 1;
  }
  function patch(id, h, from, to) {
    const sec = section(id, h);
    if (!sec) return;
    if (!sec.body.includes(from)) { missing(`${id} / ${h}: 「${from}」が見つかりません`); return; }
    sec.body = sec.body.replace(from, to);
  }
  function add(id, sec, after) {
    const u = unit(id);
    if (!u) { missing(`${id} が見つかりません`); return; }
    const i = after ? u.sections.findIndex((s) => s.h === after) : u.sections.length - 1;
    if (after && i < 0) { missing(`${id} / ${after} が見つかりません`); return; }
    u.sections.splice(i + 1, 0, sec);
    u.minutes += sec.example ? 4 : 3;
  }
  function retitle(id, title) {
    const u = unit(id);
    if (!u) { missing(`${id} が見つかりません`); return; }
    u.title = title;
  }
  // 確認テスト(一問一答)は末尾に足すので、既存の問題の識別番号は変わらない
  function check(id, c) {
    const u = unit(id);
    if (!u) { missing(`${id} が見つかりません`); return; }
    u.checks.push(c);
  }

